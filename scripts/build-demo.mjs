// Builds the browser-only demo for GitHub Pages into _site/ (or the folder given as the first argument):
//   public/                      the app as-is
//   vendor/three/build/          Three.js's single-file module (+ its MIT licence)
//   js/config.js                 replaced: DEMO = true, and the version from package.json
//   js/sign-variants.js          replaced: none (the demo uses the regular crowd signs)
// Nothing in public/ or data/ is changed, and no data files are copied.
//
//   npm run build:demo           then serve _site/ with any static file server

import crypto from 'node:crypto';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const out = path.resolve(ROOT, process.argv[2] || '_site');
const { version } = JSON.parse(fs.readFileSync(path.join(ROOT, 'package.json'), 'utf8'));

fs.rmSync(out, { recursive: true, force: true });
fs.cpSync(path.join(ROOT, 'public'), out, { recursive: true });

const threeDir = path.join(ROOT, 'node_modules', 'three');
fs.mkdirSync(path.join(out, 'vendor', 'three', 'build'), { recursive: true });
fs.copyFileSync(path.join(threeDir, 'build', 'three.module.js'), path.join(out, 'vendor', 'three', 'build', 'three.module.js'));
fs.copyFileSync(path.join(threeDir, 'LICENSE'), path.join(out, 'vendor', 'three', 'LICENSE'));
// GLTFLoader imports BufferGeometryUtils. Keep the upstream relative module layout.
for (const file of ['loaders/GLTFLoader.js', 'controls/OrbitControls.js', 'utils/SkeletonUtils.js', 'utils/BufferGeometryUtils.js']) {
  const target = path.join(out, 'vendor', 'three', 'examples', 'jsm', file);
  fs.mkdirSync(path.dirname(target), { recursive: true });
  fs.copyFileSync(path.join(threeDir, 'examples', 'jsm', file), target);
}

fs.writeFileSync(
  path.join(out, 'js', 'config.js'),
  `// Generated by scripts/build-demo.mjs for the GitHub Pages demo.\nexport const DEMO = true;\nexport const DEMO_VERSION = ${JSON.stringify(version)};\n`,
);
fs.writeFileSync(
  path.join(out, 'js', 'sign-variants.js'),
  '// Generated by scripts/build-demo.mjs for the GitHub Pages demo: the regular crowd signs only.\nexport const SIGN_VARIANTS = {};\n',
);
// Serve the files exactly as they are (no Jekyll processing on Pages).
fs.writeFileSync(path.join(out, '.nojekyll'), '');

// The demo lives under /Chesapeake-Dev-Derby/, so pages must not use root-absolute links.
const pages = fs.readdirSync(out).filter((f) => f.endsWith('.html'));
for (const page of pages) {
  const html = fs.readFileSync(path.join(out, page), 'utf8');
  const bad = html.match(/(?:href|src)="\/(?!\/)|"three":\s*"\/(?!\/)/);
  if (bad) throw new Error(`${page} uses a root-absolute path (${bad[0]}); use a relative one.`);
}

// Cache busting. GitHub Pages lets browsers keep each file for 10 minutes, so right after a deploy a
// browser could pair the new page with old scripts and styles. Every link to a page, script, style
// and Three.js gets "?v=<build>", a hash of the whole build: a new deploy is fetched as a new set,
// and an older cached set still works on its own. All modules use the same stamped URLs, so each
// module still loads once.
const files = fs.readdirSync(out, { recursive: true }).filter((f) => fs.statSync(path.join(out, f)).isFile()).sort();
const hash = crypto.createHash('sha256');
for (const f of files) hash.update(`${f.replace(/\\/g, '/')}\0`).update(fs.readFileSync(path.join(out, f)));
const build = hash.digest('hex').slice(0, 10);
const stamp = (url) => `${url}?v=${build}`;
for (const page of pages) {
  const file = path.join(out, page);
  const html = fs
    .readFileSync(file, 'utf8')
    .replace(/(\b(?:src|href)=")((?:js|css)\/[^"?#]+\.(?:js|css)|assets\/[^"?#]+|[a-z-]+\.html|\.\/)"/g, (_, attr, url) => `${attr}${stamp(url)}"`)
    .replace(/("three":\s*")(\.\/vendor\/three\/build\/three\.module\.js)"/, (_, key, url) => `${key}${stamp(url)}"`);
  fs.writeFileSync(file, html);
}
for (const f of files.filter((f) => /^js[\\/][^\\/]+\.js$/.test(f))) {
  const file = path.join(out, f);
  const js = fs
    .readFileSync(file, 'utf8')
    .replace(/(\bfrom\s*|\bimport\s*\(\s*|\bimport\s+)(['"])(\.\/[^'"?]+\.js)\2/g, (_, lead, q, url) => `${lead}${q}${stamp(url)}${q}`);
  fs.writeFileSync(file, js);
}

console.log(`Demo ${version} (build ${build}) built in ${path.relative(ROOT, out) || '.'}`);
