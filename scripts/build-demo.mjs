// Builds the browser-only demo for GitHub Pages into _site/ (or the folder given as the first argument):
//   public/                      the app as-is
//   vendor/three/build/          Three.js's single-file module (+ its MIT licence)
//   js/config.js                 replaced: DEMO = true, and the version from package.json
//   js/sign-variants.js          replaced: none (the demo uses the regular crowd signs)
// Nothing in public/ or data/ is changed, and no data files are copied.
//
//   npm run build:demo           then serve _site/ with any static file server

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const out = path.resolve(ROOT, process.argv[2] || '_site');
const { version } = JSON.parse(fs.readFileSync(path.join(ROOT, 'package.json'), 'utf8'));

fs.rmSync(out, { recursive: true, force: true });
fs.cpSync(path.join(ROOT, 'public'), out, { recursive: true });

const threeDir = path.join(ROOT, 'node_modules', 'three');
fs.mkdirSync(path.join(out, 'vendor', 'three', 'build'), { recursive: true });
fs.copyFileSync(path.join(threeDir, 'build', 'three.module.js'), path.join(out, 'vendor', 'three', 'build', 'three.module.js'));
fs.copyFileSync(path.join(threeDir, 'LICENSE'), path.join(out, 'vendor', 'three', 'LICENSE'));

fs.writeFileSync(
  path.join(out, 'js', 'config.js'),
  `// Generated by scripts/build-demo.mjs for the GitHub Pages demo.\nexport const DEMO = true;\nexport const DEMO_VERSION = ${JSON.stringify(version)};\n`,
);
fs.writeFileSync(
  path.join(out, 'js', 'sign-variants.js'),
  '// Generated by scripts/build-demo.mjs for the GitHub Pages demo: the regular crowd signs only.\nexport const SIGN_VARIANTS = {};\n',
);
// Serve the files exactly as they are (no Jekyll processing on Pages).
fs.writeFileSync(path.join(out, '.nojekyll'), '');

// The demo lives under /Chesapeake-Dev-Derby/, so pages must not use root-absolute links.
for (const page of fs.readdirSync(out).filter((f) => f.endsWith('.html'))) {
  const html = fs.readFileSync(path.join(out, page), 'utf8');
  const bad = html.match(/(?:href|src)="\/(?!\/)|"three":\s*"\/(?!\/)/);
  if (bad) throw new Error(`${page} uses a root-absolute path (${bad[0]}); use a relative one.`);
}

console.log(`Demo ${version} built in ${path.relative(ROOT, out) || '.'}`);
